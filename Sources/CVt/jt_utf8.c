int jt_utf8_next(uint8_t *st, uint32_t *acc, uint8_t b, uint32_t *out) {
    uint8_t cls = k_utf8_cls[b];
    uint8_t initial = *st;
    if (*st != 0) *acc = (*acc << 6) | (uint32_t)(b & 0x3F);
    else *acc = ((uint32_t)0xFF >> cls) & (uint32_t)b;
    *st = k_utf8_tr[*st + cls];
    if (*st == 0) {
        *out = *acc;
        *acc = 0;
        return 1;
    }
    if (*st == 12) {
        *acc = 0;
        *st = 0;
        *out = 0xFFFD;
        return initial == 0 ? 1 : 2;
    }
    *out = 0;
    return 0;
}
